#!/usr/bin/env node
// ============================================================================
// REPO HYGIENE — refuse to let credentials or player data back into the tree.
//
// This repository is public, and it has carried an Apple .p8 signing key and a
// SQLite database of player accounts. Both are the kind of mistake that is
// invisible until it is expensive, so it is checked rather than remembered.
//
//   npm run check:repo
// ============================================================================

import { execSync } from "node:child_process";

const BANNED = [
  [/\.p8$/i, "Apple private key — cannot be re-downloaded, grants API/push access"],
  [/\.(p12|pfx)$/i, "PKCS#12 keystore, usually contains a private key"],
  [/\.(keystore|jks)$/i, "Android signing keystore"],
  [/\.mobileprovision$/i, "provisioning profile"],
  [/\.pem$/i, "PEM key or certificate"],
  [/(^|\/)[^/]*\.key$/i, "private key"],
  [/\.(db|sqlite|sqlite3)$/i, "database — runtime state, and this one holds player accounts"],
  [/(^|\/)\.env$/, "environment file"],

  // Not a secret — but git keeps every version of a binary for ever, and
  // compiled output is regenerated by the build anyway. `tools/trapcard-check`
  // committed its `bin/` and `obj/` because .gitignore listed the other two
  // tools by name and nobody adds the third. A pattern is cheaper than
  // remembering.
  [/(^|\/)(bin|obj)\/.*\.(dll|pdb|exe|so|dylib)$/i, "compiled binary — regenerated by the build"],
  [/(^|\/)obj\/.*\.(cache|json)$/i, "build intermediate — regenerated by the build"],
  [/(^|\/)node_modules\//, "installed dependency — restored by npm ci"],
];

const tracked = execSync("git ls-files", { encoding: "utf8" }).split("\n").filter(Boolean);
const found = [];
for (const file of tracked) {
  for (const [pattern, why] of BANNED) {
    if (pattern.test(file)) found.push({ file, why });
  }
}

if (found.length) {
  process.stderr.write("tracked files that must not be in a public repository:\n");
  for (const f of found) process.stderr.write(`  ${f.file}\n      ${f.why}\n`);
  process.stderr.write("\nuntrack with:  git rm --cached <file>   (the file stays on disk)\n");
  process.exit(1);
}

// ---------------------------------------------------------------------------
// DOCUMENTATION DRIFT
//
// The README described three GitHub Actions workflows, two env templates and
// iOS/Android projects. None of them existed. Nothing was being checked on
// push, everybody believed it was, and that belief is the reason nobody went
// looking while a live route was minting unlimited coins.
//
// A README that claims infrastructure it does not have is worse than one that
// admits it has none, so claiming it is now a test.
// ---------------------------------------------------------------------------
import { existsSync } from "node:fs";
import { readFileSync } from "node:fs";

const readme = readFileSync("README.md", "utf8");
const drift = [];

// Naming a file that is missing is only a problem when the README is CLAIMING
// it. Saying plainly that something does not exist yet is the opposite — it is
// the honest thing we want people to do — so a line that negates itself is
// skipped. Without this the check punishes the exact behaviour it exists to
// encourage.
const NEGATED = /\bdo(?:es)? not exist\b|\bnot yet\b|\bare absent\b|\bis absent\b|\bmissing\b|\bnever (?:created|existed)\b|\bwas never\b/i;

// Per PARAGRAPH, not per line. Prose wraps: "What does not exist:" routinely
// sits on one line and the filenames it is disclaiming on the next, and a
// line-by-line check flags the second while ignoring the first.
for (const block of readme.split(/\n\s*\n/)) {
  if (NEGATED.test(block)) continue;
  for (const m of block.matchAll(/`?(\.github\/workflows\/[\w.-]+|\.env[\w.]*\.example)`?/g)) {
    if (!existsSync(m[1])) drift.push(m[1]);
  }
}
if (drift.length) {
  process.stderr.write("README.md references files that do not exist:\n");
  for (const d of [...new Set(drift)]) process.stderr.write(`  ${d}\n`);
  process.stderr.write("\nEither create them or stop claiming them. Documented-but-absent\n"
    + "infrastructure is worse than none, because it stops people looking.\n");
  process.exit(1);
}

// ---------------------------------------------------------------------------
// THE PLAYER MUST BE OURS
//
// A fresh clone once could not build a playable character: the player was a
// Starter Assets prefab whose 270 companion files were untracked, and the one
// script we had patched survived only because it predated the ignore rule.
// CI could never build a player and a new machine got a fly camera.
//
// WP-U02 replaced it with TrapPlayerController. This makes the regression
// loud: no tracked Unity script may reference Starter Assets, because anything
// that does is depending on files a clone will not have.
// ---------------------------------------------------------------------------
const unityScripts = tracked.filter((f) => f.startsWith("Unity/") && f.endsWith(".cs")
  && !f.includes("/StarterAssets/"));
const starterRefs = [];
for (const file of unityScripts) {
  const body = readFileSync(file, "utf8");
  if (/\bStarterAssets\b/.test(body)) starterRefs.push(file);
}
if (starterRefs.length) {
  process.stderr.write("tracked Unity scripts reference Starter Assets, which is not tracked:\n");
  for (const f of starterRefs) process.stderr.write(`  ${f}\n`);
  process.stderr.write("\nA fresh clone will not have those files. The player is TrapPlayerController now.\n");
  process.exit(1);
}

// The map is the one thing in server/storage that SHOULD ship.
const hasMap = tracked.includes("server/storage/map-export.json.gz");
process.stdout.write(
  `repo clean: ${tracked.length} tracked files, no credentials or databases\n` +
  (hasMap ? "map export is present, so a deploy comes up with a map\n"
          : "WARNING: no map export tracked — a deploy will have no map\n")
);
process.exit(hasMap ? 0 : 1);
